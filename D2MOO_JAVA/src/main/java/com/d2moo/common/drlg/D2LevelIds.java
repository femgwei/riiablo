    // 城镇关卡ID数组（用于快速查找）
    public static final int[] TOWN_LEVEL_IDS = {
        LEVEL_ROGUEENCAMPMENT,  // Act 1
        LEVEL_LUTGHOLEIN,        // Act 2
        LEVEL_KURASTDOCKTOWN,   // Act 3
        LEVEL_THEPANDEMONIUMFORTRESS, // Act 4
        LEVEL_HARROGATH         // Act 5
    };
    
    /**
     * 检查关卡ID是否为城镇
     * @param levelId 关卡ID
     * @return 如果是城镇返回 true，否则返回 false
     */
    public static boolean isTownLevel(int levelId) {
        for (int townId : TOWN_LEVEL_IDS) {
            if (townId == levelId) {
                return true;
            }
        }
        return false;
    }
    
    /**
     * 从关卡ID获取 Act 编号（1-5）
     * @param levelId 关卡ID
     * @return Act 编号，如果无法确定返回 0
     */
    public static int getActFromLevelId(int levelId) {
        if (levelId >= LEVEL_ROGUEENCAMPMENT && levelId <= LEVEL_MOO) {
            return 1;
        } else if (levelId >= LEVEL_LUTGHOLEIN && levelId <= LEVEL_ARCANESANCTUARY) {
            return 2;
        } else if (levelId >= LEVEL_KURASTDOCKTOWN && levelId <= LEVEL_THEPANDEMONIUMFORTRESS) {
            return 3;
        } else if (levelId >= LEVEL_OUTERSTEPPES && levelId <= LEVEL_CHAOSSANCTUARY) {
            return 4;
        } else if (levelId >= LEVEL_HARROGATH && levelId <= LEVEL_WORLDSTONECHAMBER) {
            return 5;
        }
        return 0;
    }
